function detectLanguage() {
  const saved = localStorage.getItem("hyroxsim-lang");
  if (saved && translations[saved]) return saved;

  const preferred = (navigator.languages && navigator.languages.length)
    ? navigator.languages
    : [navigator.language || "en"];

  for (const raw of preferred) {
    const lang = String(raw).toLowerCase();
    if (lang.startsWith("ko")) return "ko";
    if (lang.startsWith("ja")) return "ja";
    if (lang.startsWith("zh")) {
      if (lang.includes("hant") || lang.includes("tw") || lang.includes("hk") || lang.includes("mo")) {
        return "zh-Hant";
      }
      return "zh-Hans";
    }
    if (lang.startsWith("en")) return "en";
  }
  return "en";
}

function applyAppStoreLinks() {
  document.querySelectorAll("[data-appstore-link]").forEach((el) => {
    el.setAttribute("href", APP_STORE_URL);
  });
}

function setLanguage(lang) {
  const dictionary = translations[lang] || translations.en;
  document.documentElement.lang = lang;
  localStorage.setItem("hyroxsim-lang", lang);

  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.getAttribute("data-i18n");
    const text = dictionary[key];
    if (text) {
      node.textContent = text;
    }
  });

  document.querySelectorAll("[data-lang-button]").forEach((button) => {
    button.classList.toggle("is-active", button.getAttribute("data-lang-button") === lang);
  });
}

document.querySelectorAll("[data-lang-button]").forEach((button) => {
  button.addEventListener("click", () => {
    setLanguage(button.getAttribute("data-lang-button"));
  });
});

